/// Returns the stable column index for a tshark field name.
///
/// # Panics
///
/// Panics when `name` is not present in [`FIELDS`].
pub fn index(name: &str) -> usize {
    FIELDS
        .iter()
        .position(|candidate| *candidate == name)
        .unwrap_or_else(|| panic!("unknown field {name}"))
}
